"""
Общий интерфейс клиента СМС-провайдера — одинаковый для всех агрегаторов,
чтобы вызывающий код (app/auth.py) не знал, с каким именно агрегатором
работает. Сейчас реализован только SmsAeroClient (см. smsaero.py); при
добавлении второго агрегатора см. app/sms/__init__.py.
"""
from __future__ import annotations

import abc


class SmsError(Exception):
    """Любая ошибка отправки СМС — сетевая или неуспех на стороне
    провайдера. Вызывающий код ловит именно этот тип и показывает
    понятное сообщение вместо падения запроса."""


class SmsClient(abc.ABC):
    @abc.abstractmethod
    def send(self, phone_digits: str, text: str) -> None:
        """phone_digits — только цифры, российский номер без "+"/"8"
        (см. auth._normalize_phone_digits — 10 цифр без кода страны;
        конкретный клиент сам достраивает код страны, если он ему нужен
        в этом виде). Кидает SmsError при неудаче, ничего не возвращает
        при успехе."""

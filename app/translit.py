"""
Транслитерация кириллицы в латиницу — общий помощник там, где из русского
текста нужно получить ASCII-строку: логин по умолчанию в мастере массового
создания учётных записей (см. setup_wizard.py:_generate_login — раньше
логин оставался кириллицей, что неудобно вводить на не-русской раскладке
и нетипично для логина вообще) и slug страницы вики (см.
wiki.py:_slugify — для человекопонятного URL).

Простая посимвольная схема (не полный ГОСТ/ISO 9), этого достаточно для
читаемого результата — оба места допускают, что получившийся текст можно
поправить вручную (логин — прямо в форме мастера, slug — не меняется
после создания страницы вовсе, см. докстринг _slugify).
"""

_TRANSLIT_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Кириллица (в любом регистре) -> латиница, посимвольно, с
    сохранением регистра. Символы, которых нет в таблице (латиница, цифры,
    пробелы, дефисы, апострофы и т.п. — например, в двойных фамилиях типа
    «Петров-Водкин»), остаются как есть."""
    result = []
    for ch in text:
        translit = _TRANSLIT_MAP.get(ch.lower())
        if translit is None:
            result.append(ch)
        else:
            result.append(translit.upper() if ch.isupper() else translit)
    return "".join(result)
